    async def get_recommendation_history(
        self,
        user_id: int,
        limit: int = 10
    ) -> List[Dict]:
        """
        Get user's recommendation history.
        
        Args:
            user_id: User identifier
            limit: Number of events to return
            
        Returns:
            List of recommendation events
        """
        query = """
            SELECT 
                re.event_id,
                re.recommended_paper_ids,
                re.embedding_model,
                re.event_timestamp
            FROM recommendation_events re
            WHERE re.user_id = $1
            ORDER BY re.event_timestamp DESC
            LIMIT $2
        """
        
        results = await self.db.fetch(query, user_id, limit)
        return [dict(r) for r in results]

    async def check_embedding_update_trigger(
        self,
        user_id: int
    ) -> bool:
        """
        Check if user has enough new interactions to trigger embedding update.
        
        Args:
            user_id: User identifier
            
        Returns:
            bool: True if update should be triggered
        """
        logger.debug(
            "Checking embedding update trigger",
            user_id=user_id
        )
        
        # Get last embedding update time
        state_query = """
            SELECT last_embedding_update_minilm, last_embedding_update_specter
            FROM user_recommendation_state
            WHERE user_id = $1
        """
        
        state = await self.db.fetchrow(state_query, user_id)
        
        if not state:
            logger.debug("No state found, trigger update", user_id=user_id)
            return True
        
        # Use most recent update time
        last_update = max(
            state['last_embedding_update_minilm'] or datetime.min,
            state['last_embedding_update_specter'] or datetime.min
        )
        
        # Count interactions since last update
        count_query = """
            SELECT COUNT(*)
            FROM user_interactions
            WHERE user_id = $1
              AND created_at > $2
              AND interaction_type IN ('save', 'cite', 'download', 'like')
        """
        
        try:
            count = await self.db.fetchval(count_query, user_id, last_update)
            
            # Trigger if 5+ meaningful interactions
            should_trigger = count >= 5
            
            logger.debug(
                "Embedding update check complete",
                user_id=user_id,
                interactions_since_update=count,
                should_trigger=should_trigger
            )
            
            return should_trigger
            
        except Exception as e:
            logger.error(
                "Embedding update check failed",
                user_id=user_id,
                error=str(e),
                exc_info=True
            )
            raise