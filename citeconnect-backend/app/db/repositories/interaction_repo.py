    async def create_interaction(
        self,
        user_id: int,
        paper_id: str,
        interaction_type: str,
        duration_seconds: Optional[int] = None,
        source: Optional[str] = None,
        position: Optional[int] = None,
        session_id: Optional[str] = None
    ) -> asyncpg.Record:
        """
        Record a user-paper interaction.
        NOTE: interaction_strength is GENERATED by database based on interaction_type.
        """
        logger.info(
            "Creating interaction",
            user_id=user_id,
            paper_id=paper_id,
            interaction_type=interaction_type
        )
        
        # Build context JSON object
        context = {}
        if source:
            context['source'] = source
        if position is not None:
            context['position'] = position
        if session_id:
            context['session_id'] = session_id
        
        # Serialize to JSON string for PostgreSQL JSONB column
        import json
        context_json = json.dumps(context) if context else None
        
        query = """
            INSERT INTO user_interactions (
                user_id, paper_id, interaction_type,
                duration_seconds, context
            )
            VALUES ($1, $2, $3, $4, $5::jsonb)
            RETURNING *
        """
        
        try:
            result = await self.db.fetchrow(
                query,
                user_id,
                paper_id,
                interaction_type,
                duration_seconds,
                context_json  # Pass JSON string
            )
            
            logger.info(
                "Interaction created",
                user_id=user_id,
                paper_id=paper_id,
                type=interaction_type,
                strength=result['interaction_strength']
            )
            
            return result
            
        except Exception as e:
            logger.error(
                "Interaction creation failed",
                user_id=user_id,
                paper_id=paper_id,
                error=str(e),
                exc_info=True
            )
            raise
    
    async def get_user_interactions(
        self,
        user_id: int,
        limit: Optional[int] = None,
        min_strength: Optional[float] = None,
        since: Optional[datetime] = None
    ) -> List[asyncpg.Record]:
        """
        Get user's interaction history.
        
        Args:
            user_id: User identifier
            limit: Maximum interactions to return
            min_strength: Minimum interaction strength
            since: Only interactions after this time
            
        Returns:
            List[Record]: Interaction records
        """
        logger.debug(
            "Getting user interactions",
            user_id=user_id,
            limit=limit,
            min_strength=min_strength
        )
        
        query = """
            SELECT ui.*, p.title, p.domain, p.year
            FROM user_interactions ui
            JOIN papers p ON ui.paper_id = p.paper_id
            WHERE ui.user_id = $1
        """
        
        params = [user_id]
        param_idx = 2
        
        if min_strength is not None:
            query += f" AND ui.interaction_strength >= ${param_idx}"
            params.append(min_strength)
            param_idx += 1
        
        if since:
            query += f" AND ui.created_at >= ${param_idx}"
            params.append(since)
            param_idx += 1
        
        query += " ORDER BY ui.created_at DESC"
        
        if limit:
            query += f" LIMIT ${param_idx}"
            params.append(limit)
        
        try:
            results = await self.db.fetch(query, *params)
            
            logger.debug(
                "Interactions retrieved",
                user_id=user_id,
                count=len(results)
            )
            
            return results
            
        except Exception as e:
            logger.error(
                "Interactions retrieval failed",
                user_id=user_id,
                error=str(e),
                exc_info=True
            )
            raise
    
    async def get_interaction_counts(
        self,
        user_id: int,
        days: int = 30
    ) -> Dict[str, int]:
        """
        Get counts of different interaction types.
        
        Args:
            user_id: User identifier
            days: Look back period in days
            
        Returns:
            Dict mapping interaction type to count
        """
        logger.debug(
            "Getting interaction counts",
            user_id=user_id,
            days=days
        )
        
        query = """
            SELECT 
                interaction_type,
                COUNT(*) as count
            FROM user_interactions
            WHERE user_id = $1
              AND created_at >= NOW() - INTERVAL '1 day' * $2
            GROUP BY interaction_type
        """
        
        try:
            results = await self.db.fetch(query, user_id, days)
            
            counts = {row['interaction_type']: row['count'] for row in results}
            
            logger.debug(
                "Interaction counts retrieved",
                user_id=user_id,
                counts=counts
            )
            
            return counts
            
        except Exception as e:
            logger.error(
                "Interaction counts retrieval failed",
                user_id=user_id,
                error=str(e),
                exc_info=True
            )
            raise
    
