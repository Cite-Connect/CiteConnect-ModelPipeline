    async def add_paper_filter(
        self,
        user_id: int,
        paper_id: str,
        filter_type: str,
        reason: Optional[str] = None
    ) -> asyncpg.Record:
        """
        Add paper to user's filter list (don't show again).
        
        Args:
            user_id: User identifier
            paper_id: Paper to filter
            filter_type: 'not_interested', 'already_read', 'saved', 'dismissed'
            reason: Optional reason
            
        Returns:
            Record: Created filter record
        """
        logger.info(
            "Adding paper filter",
            user_id=user_id,
            paper_id=paper_id,
            filter_type=filter_type
        )
        
        query = """
            INSERT INTO user_paper_filters (
                user_id, paper_id, filter_type
            )
            VALUES ($1, $2, $3)
            ON CONFLICT (user_id, paper_id)
            DO UPDATE SET
                filter_type = EXCLUDED.filter_type
            RETURNING *
        """
        
        try:
            result = await self.db.fetchrow(
                query,
                user_id,
                paper_id,
                filter_type
            )
            
            logger.info(
                "Paper filter added",
                user_id=user_id,
                paper_id=paper_id
            )
            
            return result
            
        except Exception as e:
            logger.error(
                "Paper filter creation failed",
                user_id=user_id,
                paper_id=paper_id,
                error=str(e),
                exc_info=True
            )
            raise
    
    async def get_filtered_papers(
        self,
        user_id: int,
        filter_types: Optional[List[str]] = None
    ) -> List[str]:
        """
        Get list of paper IDs user has filtered.
        
        Args:
            user_id: User identifier
            filter_types: Optional filter types to include
            
        Returns:
            List[str]: Paper IDs
        """
        logger.debug(
            "Getting filtered papers",
            user_id=user_id,
            filter_types=filter_types
        )
        
        query = "SELECT paper_id FROM user_paper_filters WHERE user_id = $1"
        params = [user_id]
        
        if filter_types:
            query += " AND filter_type = ANY($2::text[])"
            params.append(filter_types)
        
        try:
            results = await self.db.fetch(query, *params)
            paper_ids = [row['paper_id'] for row in results]
            
            logger.debug(
                "Filtered papers retrieved",
                user_id=user_id,
                count=len(paper_ids)
            )
            
            return paper_ids
            
        except Exception as e:
            logger.error(
                "Filtered papers retrieval failed",
                user_id=user_id,
                error=str(e),
                exc_info=True
            )
            raise
    
